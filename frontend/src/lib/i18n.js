export const LANG_KEY = 'bluerock_lang'

export function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY)
    if (saved) return saved === 'en' ? 'en' : 'fr'
  } catch {}
  const nav = typeof navigator !== 'undefined' ? (navigator.language || 'fr') : 'fr'
  return nav.toLowerCase().startsWith('en') ? 'en' : 'fr'
}

export function t(lang, key) {
  if (key === undefined) {
    key = lang
    lang = detectLang()
  }
  return (dict[lang] || dict.fr)[key] || dict.fr[key] || key
}

export function fmtPrice(lang, n, digits = 2) {
  if (n == null) return '—'
  return n.toLocaleString(lang === 'en' ? 'en-US' : 'fr-FR', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  })
}

export function fmtMoney(lang, n, currency, digits = 2) {
  if (n == null) return '—'
  const formatted = fmtPrice(lang, n, digits)
  return currency === 'NGN' ? `₦${formatted}` : `${formatted} FCFA`
}

export function fmtPriceCur(lang, n, currency, digits = 2) {
  if (n == null) return '—'
  const formatted = fmtPrice(lang, n, digits)
  return currency === 'NGN' ? `₦${formatted}` : `FCFA ${formatted}`
}

export function fmtCompact(lang, n) {
  if (n == null) return '—'
  const locale = lang === 'en' ? 'en-US' : 'fr-FR'
  if (Math.abs(n) >= 1e9) return (n / 1e9).toLocaleString(locale, { maximumFractionDigits: 2 }) + (lang === 'en' ? 'B' : ' Md')
  if (Math.abs(n) >= 1e6) return (n / 1e6).toLocaleString(locale, { maximumFractionDigits: 2 }) + (lang === 'en' ? 'M' : ' M')
  if (Math.abs(n) >= 1e3) return (n / 1e3).toLocaleString(locale, { maximumFractionDigits: 1 }) + 'K'
  return n.toLocaleString(locale, { maximumFractionDigits: 0 })
}

export function fmtChange(lang, n, digits = 2) {
  if (n == null) return '—'
  const s = n.toLocaleString(lang === 'en' ? 'en-US' : 'fr-FR', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  })
  return (n > 0 ? '+' : '') + s + '%'
}

export function timeAgo(lang, iso) {
  if (!iso) return ''
  const diff = Date.now() - new Date(iso).getTime()
  if (Number.isNaN(diff)) return ''
  const min = Math.floor(diff / 60000)
  if (min < 1) return t(lang, 'timeAgoNow')
  if (min < 60) return t(lang, 'timeAgoMin').replace('{n}', min)
  const hours = Math.floor(min / 60)
  if (hours < 24) return t(lang, 'timeAgoHour').replace('{n}', hours)
  return t(lang, 'timeAgoDay').replace('{n}', Math.floor(hours / 24))
}

export function fmtDateTime(lang, iso) {
  if (!iso) return ''
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return ''
  const pad = n => String(n).padStart(2, '0')
  if (lang === 'en') {
    return `${pad(d.getMonth() + 1)}/${pad(d.getDate())}/${d.getFullYear()} ${d.getHours() % 12 || 12}:${pad(d.getMinutes())} ${d.getHours() < 12 ? 'AM' : 'PM'}`
  }
  return `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}
